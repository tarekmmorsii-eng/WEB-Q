const OUTPUT_FILE = path.join(__dirname, 'constants', 'mutashabiha_data_full.json');
const INPUT_FILE = path.join(__dirname, 'public', 'quran.json');

try {
    const quranData = JSON.parse(fs.readFileSync(INPUT_FILE, 'utf8'));

    // سورة البقرة تبدأ من آية رقم 8 في المصحف الكلي (1-7 للفاتحة)
    // لذا الآية X في البقرة هي X + 7
    const getAbs = (n) => n + 7;

    const outputByJuz = {};

    // خريطة لتجميع المتشابهات لكل سطر (rule)
    // Map<phrase, { type, color, ayahs[] }>
    const tempGroups = new Map();

    Object.entries(userData.categories).forEach(([catKey, cat]) => {
        Object.entries(cat.rules).forEach(([phrase, ayahs]) => {
            const key = `${cat.type}_${phrase}`;
            tempGroups.set(key, {
                phrase: phrase,
                type: cat.type,
                color: cat.color,
                ayahs: ayahs.map(getAbs)
            });
        });
    });

    // تحويل المجموعات إلى الصيغة النهائية
    // الصيغة: { "juz": [ { src: {ayah}, muts: [ {ayah, rule, type, color} ] } ] }
    tempGroups.forEach(group => {
        group.ayahs.forEach(srcAbs => {
            // تحديد الجزء (Juz) لهذه الآية
            // سنفترض مبدئياً جزء 1-3 للبقرة ولكن الأفضل جلبها من quran.json
            let juz = 1;
            const surah = quranData.data.surahs.find(s => s.number === 2);
            const ayah = surah.ayahs.find(a => a.number === srcAbs);
            if (ayah) juz = ayah.juz;

            if (!outputByJuz[juz]) outputByJuz[juz] = [];

            let entry = outputByJuz[juz].find(e => e.src.ayah === srcAbs);
            if (!entry) {
                entry = { src: { ayah: srcAbs }, muts: [] };
                outputByJuz[juz].push(entry);
            }

            // إضافة كل الآيات الأخرى في نفس المجموعة كمتشابهات
            group.ayahs.forEach(mutAbs => {
                if (srcAbs === mutAbs) return;

                // منع التكرار
                if (!entry.muts.find(m => m.ayah === mutAbs && m.rule === group.phrase)) {
                    entry.muts.push({
                        ayah: mutAbs,
                        rule: group.phrase,
                        type: group.type,
                        color: group.color
                    });
                }
            });
        });
    });

    fs.writeFileSync(OUTPUT_FILE, JSON.stringify(outputByJuz, null, 0));
    console.log(`✅ Done. Generated ${tempGroups.size} groups in ${OUTPUT_FILE}`);

} catch (e) {
    console.error(e);
}
