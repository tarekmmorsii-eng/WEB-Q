const getTypeString = (t: number): 'full' | 'quarter' | 'half' | 'three-quarter' => {
  switch (t) {
    case 1: return 'quarter';
    case 2: return 'half';
    case 3: return 'three-quarter';
    default: return 'full';
  }
};

export const JUZ_SECTIONS = QUARTERS_DATA.map((data, index) => {
  const [page, surahNum, ayahNum, typeCode, text] = data;
  const surah = SURAH_NAMES.find(s => s.number === surahNum);
  const surahName = surah ? surah.name : `سورة ${surahNum}`;

  // Calculate juz from index (8 per juz)
  const juz = Math.floor(index / 8) + 1;

  // Calculate hizb from index (4 per hizb)
  const hizb = Math.floor(index / 4) + 1;

  return {
    id: `qs-${index}`,
    page,
    text,
    subtitle: `${surahName}، آية ${ayahNum}`,
    surahNum,
    ayahNum,
    juz,
    hizb,
    type: getTypeString(typeCode)
  };
});
