// Bound Google Apps Script for the feedback spreadsheet.
// Update the EXISTING Web App deployment after replacing its code (see feedback_setup.md).
const SHEET_NAME = 'الورقة1';
const SCREENSHOT_MAX_BYTES = 1024 * 1024;

function plainCell(value, maxLength) {
    const text = String(value == null ? '' : value).slice(0, maxLength || 20000);
    return /^[=+\-@\t\r\n]/.test(text) ? "'" + text : text;
}

function saveFeedbackScreenshot(screenshot, feedbackId) {
    if (!screenshot) return null;
    if (screenshot.mimeType !== 'image/jpeg' || typeof screenshot.base64 !== 'string' ||
        screenshot.base64.length > Math.ceil(SCREENSHOT_MAX_BYTES / 3) * 4 ||
        !/^[A-Za-z0-9+/]+={0,2}$/.test(screenshot.base64)) {
        throw new Error('Invalid screenshot');
    }
    const bytes = Utilities.base64Decode(screenshot.base64);
    if (bytes.length < 4 || bytes.length > SCREENSHOT_MAX_BYTES ||
        (bytes[0] & 255) !== 255 || (bytes[1] & 255) !== 216 || (bytes[2] & 255) !== 255 ||
        (bytes[bytes.length - 2] & 255) !== 255 || (bytes[bytes.length - 1] & 255) !== 217) {
        throw new Error('Invalid JPEG screenshot');
    }
    const properties = PropertiesService.getScriptProperties();
    let folderId = properties.getProperty('FEEDBACK_SCREENSHOTS_FOLDER_ID');
    let folder;
    if (folderId) {
        folder = DriveApp.getFolderById(folderId);
    } else {
        folder = DriveApp.createFolder('Mushaf feedback screenshots');
        properties.setProperty('FEEDBACK_SCREENSHOTS_FOLDER_ID', folder.getId());
    }
    // No public sharing: screenshots remain private to the folder's authorized viewers.
    const name = 'feedback-' + feedbackId + '.jpg';
    return folder.createFile(Utilities.newBlob(bytes, 'image/jpeg', name));
}

function doPost(e) {
    const lock = LockService.getScriptLock();
    let uploadedFile = null;
    let rowSaved = false;
    try {
        lock.waitLock(10000);
        if (!e || !e.postData || e.postData.contents.length > 1600000) throw new Error('Invalid request');
        const data = JSON.parse(e.postData.contents);
        if (typeof data.message !== 'string' || !data.message.trim() || data.message.length > 10000) throw new Error('Invalid message');
        const doc = SpreadsheetApp.getActiveSpreadsheet();
        const sheet = doc.getSheetByName(SHEET_NAME);
        if (!sheet) throw new Error('Feedback sheet not found');
        const device = data.deviceInfo || {};
        // Generated by the server, never taken from the submitted payload.
        const feedbackId = Utilities.getUuid();

        const schema = feedbackSchema(sheet);
        uploadedFile = saveFeedbackScreenshot(data.screenshot, feedbackId);
        const nextRow = appendFeedbackRow(sheet, feedbackRow(schema, data, new Date(), feedbackId, uploadedFile));
        rowSaved = true;
        // Preserve the existing owner's email notification. A mail failure must
        // not delete an attachment after its row has already been saved.
        try {
            MailApp.sendEmail('tarek.m.morsii@gmail.com', 'ملاحظة جديدة في تطبيق المصحف [feedback:' + feedbackId + ']',
                'الرقم المرجعي: ' + feedbackId + '\nتم استلام ملاحظة جديدة:\n' + data.message + '\n\n' + doc.getUrl() +
                (uploadedFile ? '\nلقطة الشاشة: ' + uploadedFile.getUrl() : ''));
        } catch (mailError) {
            console.warn('Feedback saved; email notification failed.');
        }
        return ContentService.createTextOutput(JSON.stringify({ result: 'success', row: nextRow }))
            .setMimeType(ContentService.MimeType.JSON);
    } catch (error) {
        // Avoid leaving an unattached screenshot if writing the feedback row fails.
        if (uploadedFile && !rowSaved) { try { uploadedFile.setTrashed(true); } catch (_) {} }
        return ContentService.createTextOutput(JSON.stringify({ result: 'error', error: String(error.message || error) }))
            .setMimeType(ContentService.MimeType.JSON);
    } finally {
        if (lock.hasLock()) lock.releaseLock();
    }
}

