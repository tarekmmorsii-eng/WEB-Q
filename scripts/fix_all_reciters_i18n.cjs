// MAIN: Process all files
// ═══════════════════════════════════════════════════════════════════
function main() {
  const expectedKeys = Object.keys(AR_RECITERS);
  let totalUpdated = 0;
  let totalErrors = 0;

  console.log('════════════════════════════════════════════════════');
  console.log('  تحديث شامل لأسماء القراء في جميع اللغات');
  console.log('════════════════════════════════════════════════════\n');

  for (const [lang, reciters] of Object.entries(ALL_RECITERS)) {
    const filePath = path.join(DIR, `${lang}.json`);
    
    try {
      // Read existing file
      const raw = fs.readFileSync(filePath, 'utf8');
      const data = JSON.parse(raw);
      
      // Replace reciters section with our definitive version
      data.reciters = { ...reciters };
      
      // Verify all keys are present
      const keys = Object.keys(data.reciters);
      const missing = expectedKeys.filter(k => !keys.includes(k));
      
      if (missing.length > 0) {
        console.error(`  ❌ ${lang}: MISSING KEYS: ${missing.join(', ')}`);
        totalErrors++;
        continue;
      }
      
      // Write back with proper formatting
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
      
      console.log(`  ✅ ${lang}: ${keys.length}/48 keys updated`);
      totalUpdated++;
    } catch (err) {
      console.error(`  ❌ ${lang}: ERROR - ${err.message}`);
      totalErrors++;
    }
  }

  console.log('\n════════════════════════════════════════════════════');
  console.log(`  النتيجة: ${totalUpdated} ملف تم تحديثه، ${totalErrors} أخطاء`);
  console.log('════════════════════════════════════════════════════');
  
  // Verify specific bottom-list reciters
  console.log('\n--- التحقق من أسماء أسفل القائمة ---');
  const bottomKeys = ['basfar', 'banna', 'mustafa_ismail', 'tablawi', 'shatri', 'sowaid'];
  for (const lang of ['ar', 'ja', 'ko', 'zh', 'ru', 'tr', 'hi', 'bn']) {
    const fp = path.join(DIR, `${lang}.json`);
    const d = JSON.parse(fs.readFileSync(fp, 'utf8'));
    console.log(`\n  ${lang}:`);
    for (const k of bottomKeys) {
      console.log(`    ${k}: ${d.reciters[k]}`);
    }
  }
}

main();