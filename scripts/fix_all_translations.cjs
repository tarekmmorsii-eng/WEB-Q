// تطبيق الترجمات على كل ملف
const files = fs.readdirSync(langDir).filter(f => f.endsWith('.json'));

for (const file of files) {
  const lang = file.replace('.json', '');
  if (lang === 'ar' || lang === 'en') {
    console.log(`Skipping: ${file} (already correct)`);
    continue;
  }
  
  const filePath = path.join(langDir, file);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const trans = translations[lang];
  
  if (!trans) {
    console.log(`WARNING: No translations for ${lang}, skipping`);
    continue;
  }
  
  let changed = 0;
  for (const [key, value] of Object.entries(trans)) {
    if (data[key] !== undefined && data[key] !== value) {
      data[key] = value;
      changed++;
    }
  }
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`Updated: ${file} (${changed} keys changed)`);
}

console.log('\nDone! All translations corrected.');