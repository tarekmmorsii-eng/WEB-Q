const convertCross = (groups) => {
    const result = [];
    groups.forEach((g, gIdx) => {
        g.ayahs.forEach(src => {
            const others = g.ayahs.filter(o => o.surah !== src.surah || o.ayah !== src.ayah);
            if (others.length > 0) {
                result.push({
                    id: `mut_cross_${gIdx}_${src.surah}_${src.ayah}`,
                    sourceAyah: { surahNumber: src.surah, ayahNumber: src.ayah, absoluteAyahNumber: getAbsolute(src.surah, src.ayah) },
                    similarAyahs: others.map(o => ({
                        surahNumber: o.surah, ayahNumber: o.ayah, absoluteAyahNumber: getAbsolute(o.surah, o.ayah),
                        rule: g.rule, ruleType: g.type
                    }))
                });
            }
        });
    });
    return result;
};

const convert = (surah, groups) => {
    const result = [];
    groups.forEach((g, gIdx) => {
        g.ayahs.forEach(src => {
            const others = g.ayahs.filter(o => o !== src);
            if (others.length > 0) {
                result.push({
                    id: `mut_${surah}_${gIdx}_${src}`,
                    sourceAyah: { surahNumber: surah, ayahNumber: src, absoluteAyahNumber: getAbsolute(surah, src) },
                    similarAyahs: others.map(o => ({
                        surahNumber: surah, ayahNumber: o, absoluteAyahNumber: getAbsolute(surah, o),
                        rule: g.rule, ruleType: g.type
                    }))
                });
            }
        });
    });
    return result;
};

